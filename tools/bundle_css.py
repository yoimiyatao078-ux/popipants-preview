# Flattens css/main.css (@import chain) into css/bundle.css so the browser makes 1 request instead of ~21 serial ones.
# url() paths are rewritten relative to css/. Re-run after editing any imported file.
import re,os
def load(path):
    base=os.path.dirname(path); out=[]
    for line in open(path).read().splitlines(True):
        m=re.match(r"\s*@import url\('([^']+)'\);",line)
        if m: out.append(load(os.path.normpath(os.path.join(base,m.group(1))))); continue
        out.append(line)
    css=''.join(out)
    def fix(m):
        u=m.group(2)
        if re.match(r'(data:|https?:|/|#)',u): return m.group(0)
        rel=os.path.relpath(os.path.normpath(os.path.join(base,u)),'css')
        return 'url(%s%s%s)'%(m.group(1),rel,m.group(1))
    if base!='css': css=re.sub(r"url\((['\"]?)([^)'\"]+)\1\)",fix,css)
    return '/* ---- %s ---- */\n'%path+css+'\n'
open('css/bundle.css','w').write('/* GENERATED by tools/bundle_css.py from css/main.css — do not edit by hand */\n'+load('css/main.css'))
print(os.path.getsize('css/bundle.css'))
