"""Builds the site's critter files from designs.py.
Usage (from the project folder):  python tools/critters/build.py
Writes: js/critter-shapes.js, css/critters.css
Edit MOODS below to choose which critters appear in which theme."""
import os, re, json, sys
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.join(here, '..', '..')
sys.path.insert(0, here)
from designs import items, CSS

# theme -> list of (critter key, how it moves: fly | drift | hop)
MOODS = {
  'pink': [('pbutterfly-1', 'fly'), ('pbutterfly-2', 'fly')],
  'blue': [('hibiscus-1', 'drift'), ('hibiscus-2', 'drift'), ('hibiscus-3', 'drift'), ('hibiscus-4', 'drift'), ('hibiscus-5', 'drift')],
  'red':  [('ladybug-3', 'hop')],
  'goth': [('goth-1', 'fly'), ('goth-5', 'fly')],
}

shapes = {}
for theme, lst in MOODS.items():
    for key, _ in lst:
        inner = items[key][2]
        inner = inner.replace('id="', 'id="cr-' + key + '-').replace('url(#', 'url(#cr-' + key + '-')
        shapes[key] = '<svg viewBox="0 0 200 200" aria-hidden="true" focusable="false">' + inner + '</svg>'

js = ('/* AUTO-GENERATED by tools/critters/build.py — do not edit by hand.\n'
      '   To change critters: edit tools/critters/designs.py or MOODS in build.py, then run the build. */\n'
      'window.POPI_CRITTERS = ' + json.dumps({'moods': {t: [{'key': k, 'move': m} for k, m in l] for t, l in MOODS.items()}, 'shapes': shapes}, ensure_ascii=False, indent=1) + ';\n')
open(os.path.join(root, 'js', 'critter-shapes.js'), 'w').write(js)

# scope the design CSS under .critter and prefix keyframes so nothing clashes with the site
css = CSS
names = re.findall(r'@keyframes (\w+)', css)
for n in names:
    css = re.sub(r'animation:%s\b' % n, 'animation:cr-%s' % n, css)
    css = css.replace('@keyframes %s{' % n, '@keyframes cr-%s{' % n)
out = []
for line in css.strip().split('\n'):
    if line.startswith('.cr{'):
        out.append('.critter .cr' + line[3:])
    elif line.startswith('.cr '):
        out.append('.critter ' + line)
    elif line.startswith('.') :
        out.append('.critter .cr ' + line)
    else:
        out.append(line)
open(os.path.join(root, 'css', 'critters.css'), 'w').write(
  '/* =====================================================================\n'
  '   CRITTERS (the little animals wandering around, one set per theme)\n'
  '   Part 1 is AUTO-GENERATED by tools/critters/build.py (their own wing-flap etc.).\n'
  '   Part 2 (bottom) is the wandering layer — safe to edit by hand.\n'
  '   ===================================================================== */\n'
  + '\n'.join(out) + '\n' + open(os.path.join(here, 'critters-wander.css')).read())
print('built', len(shapes), 'critters')
